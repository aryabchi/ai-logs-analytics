from crewai import Agent, LLM
from tools import parse_incidents, generate_markdown_report

# Локальная модель
llm = LLM(
    model="ollama/llama3.1:8b",
    api_key="dummy",
    base_url="http://localhost:11434",
    temperature=0.01,
)

# Агент 1: анализ логов
log_analyst = Agent(
    role="Аналитик логов",
    goal=(
        "ВЫЗОВИ инструмент parse_incidents ОДИН раз со всем содержимым лога. "
        "ВЕРНИ ТОЛЬКО ЧИСТЫЙ РЕЗУЛЬТАТ ИНСТРУМЕНТА БЕЗ КАКИХ-ЛИБО ИЗМЕНЕНИЙ, "
        "пояснений, кавычек или дополнительного текста. "
        "Твой вывод ДОЛЖЕН начинаться с '{' и заканчиваться '}'."
    ),
    backstory="Специалист по извлечению структурированных данных из логов",
    llm=llm,
    tools=[parse_incidents],
    verbose=False,
    max_iter=1,  # ← критически важно: запретить повторные попытки
    allow_delegation=False,
)

# Агент 2: генерация отчёта
report_writer = Agent(
    role="Технический писатель",
    goal=(
        "СФОРМИРУЙ отчёт на русском языке:\n"
        "1. ПОДВЕДИ итог по инцидентам: сколько их всего, распределение по критичности\n"
        "2. ДОБАВЬ краткий анализ каждой ошибки (1 предложение на инцидент)\n"
        "3. ВЫЗОВИ инструмент generate_markdown_report с итогом по инцидентам и кратким анализом ошибок\n"
        "4. ВЕРНИ результат инструмента как финальный ответ\n"
        "\nЗАПРЕЩЕНО:\n"
        "- Изменять шаблон "
        "- Выдумывать данные об инцидентах\n"
        "- Добавлять информацию, которой нет в результатах анализа"
    ),
    backstory=(
        "Опытный технический писатель, специализирующийся на документировании инцидентов. "
        "Всегда работаешь ТОЛЬКО с предоставленными данными. "
        "Никогда не выдумываешь детали."
    ),
    llm=llm,
    tools=[generate_markdown_report],
    verbose=False,
    max_iter=4,
    allow_delegation=False,
)
